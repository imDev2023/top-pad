// `pnpm --filter @top-pad/vamp-shield generate`: writes src/confusables.generated.ts from UTS #39's confusables.txt, the
// data behind the skeleton that Vamp Shield's keys are built on (spec 6.2). The file is pinned by version and SHA-256,
// and nothing is written unless the download matches, so a regenerated table is always the one that was reviewed.
// Pass a path to read a local copy instead of downloading; the same hash applies.
//
// Moving to a newer Unicode version: since 17.0.0 the data lives under https://www.unicode.org/Public/<version>/security/
// (https://www.unicode.org/Public/security/ stops at 16.0.0). Update VERSION and SHA256 together and regenerate;
// FOLD_VERSION follows, and every stored key must then be recomputed, because skeletons are not stable across versions.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { decodeConfusables } from "../src/confusables";

const VERSION = "18.0.0";
const SOURCE = `https://www.unicode.org/Public/${VERSION}/security/confusables.txt`;
const SHA256 = "6ed3ee967c9dfdf6677d563c9985182fbc50a2efb7d6059cd57b2e2ce18f5b92";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "confusables.generated.ts");

async function load(): Promise<Buffer> {
  const local = process.argv[2];
  if (local) return readFileSync(local);
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

const bytes = await load();
const hash = createHash("sha256").update(bytes).digest("hex");
if (hash !== SHA256) throw new Error(`confusables.txt has SHA-256 ${hash}, not the pinned ${SHA256}; nothing written.`);
const text = bytes.toString("utf8");

const header = (pattern: RegExp) => {
  const value = pattern.exec(text)?.[1]?.trim();
  if (!value) throw new Error(`confusables.txt has no header line matching ${pattern}`);
  return value;
};
if (header(/^# Version: (\S+)$/m) !== VERSION) throw new Error(`confusables.txt is not version ${VERSION}`);
const date = header(/^# Date: (\d{4}-\d{2}-\d{2})/m);
// The file's own copyright and terms lines travel with the data, as the Unicode License asks.
const notice = [header(/^# (©.*)$/m), header(/^# (For terms of use.*)$/m)];

const hex = (cp: number) => cp.toString(16).toUpperCase().padStart(4, "0");
const parseCodePoint = (h: string) => {
  if (!/^[0-9A-F]{4,6}$/.test(h)) throw new Error(`not a code point: "${h}"`);
  return Number.parseInt(h, 16);
};

// Each line: source ; target ; MA # comment. The source is one code point, the target one or more.
const prototypes = new Map<number, number[]>();
for (const line of text.split("\n")) {
  const data = line.split("#", 1)[0]!.trim();
  if (data === "") continue;
  const [source, target, type, ...rest] = data.split(";").map((f) => f.trim());
  if (!source || !target || type !== "MA" || rest.length > 0) throw new Error(`unexpected line: ${line}`);
  const from = parseCodePoint(source);
  if (prototypes.has(from)) throw new Error(`U+${hex(from)} is mapped twice`);
  prototypes.set(from, target.split(/\s+/).map(parseCodePoint));
}

// One line per prototype, prototypes and sources in code point order, so the output only changes when the data does.
const groups = new Map<string, { to: number[]; froms: number[] }>();
for (const [from, to] of prototypes) {
  const key = to.join(" ");
  const group = groups.get(key) ?? { to, froms: [] };
  group.froms.push(from);
  groups.set(key, group);
}
const byCodePoints = (x: number[], y: number[]) => {
  for (let i = 0; i < Math.min(x.length, y.length); i++) if (x[i] !== y[i]) return x[i]! - y[i]!;
  return x.length - y.length;
};
const lines = [...groups.values()]
  .sort((a, b) => byCodePoints(a.to, b.to))
  .map(({ to, froms }) => `${to.map(hex).join(" ")}:${froms.sort((a, b) => a - b).map(hex).join(" ")}`);
const encoded = `\n${lines.join("\n")}\n`;

// What the runtime will read back must be exactly what the file says.
const decoded = decodeConfusables(encoded);
if (decoded.size !== prototypes.size) throw new Error(`decoded ${decoded.size} mappings, expected ${prototypes.size}`);
for (const [from, to] of prototypes) {
  if (decoded.get(from) !== String.fromCodePoint(...to)) throw new Error(`U+${hex(from)} does not decode to its prototype`);
}

writeFileSync(
  out,
  `// Generated by scripts/generate-confusables.ts (\`pnpm --filter @top-pad/vamp-shield generate\`); never edit by hand.
// Source: ${SOURCE}
// UTS #39 confusables version ${VERSION}, dated ${date}, ${prototypes.size} mappings.
// SHA-256 ${SHA256}
// ${notice.join("\n// ")}
// One line per prototype: its code points, a colon, then every code point whose prototype it is, in hex.

export const CONFUSABLES_VERSION = "${VERSION}";

export const CONFUSABLES = \`${encoded}\`;
`,
);
console.log(`confusables ${VERSION} (${date}): ${prototypes.size} mappings onto ${lines.length} prototypes, ${encoded.length} bytes`);
